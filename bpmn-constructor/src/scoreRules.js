const STATUS_FAILED = 'failed';

/**
 * Человекочитаемая дельта правил после принятия улучшения:
 * {fixed: [...], broken: [...]} из заголовков RULE_MESSAGES. Пустой ответ —
 * правил не тронуто; молчать в этом случае значит оставить пользователя без
 * объяснения, почему балл не сдвинулся.
 */
export function describeRulesDelta(delta) {
    const rules = (delta && delta.rules) || {};
    const fixed = [];
    const broken = [];
    Object.keys(rules).forEach((key) => {
        const title = (RULE_MESSAGES[key] || {}).title;
        if (!title) return;
        if (rules[key].after === STATUS_FAILED) broken.push(title);
        else fixed.push(title);
    });
    return { fixed, broken };
}
