_BY_ID: Dict[str, Scenario] = {s.id: s for s in SCENARIOS}


def all_scenarios() -> List[Scenario]:
    return list(SCENARIOS)


def get(scenario_id: str) -> Scenario:
    try:
        return _BY_ID[scenario_id]
    except KeyError:
        raise KeyError(
            f"неизвестный сценарий «{scenario_id}»; есть: "
            + ", ".join(_BY_ID)) from None


def select(spec: Optional[str]) -> List[Scenario]:
    """Выбор по аргументу `--scenarios`: `all` либо имена через запятую.

    Порядок всегда порядок SCENARIOS — иначе два прогона нельзя сравнивать по
    строкам таблицы.
    """
    if not spec or spec.strip().lower() in {"all", "все", "*"}:
        return all_scenarios()
    wanted = [name.strip() for name in spec.split(",") if name.strip()]
    unknown = [name for name in wanted if name not in _BY_ID]
    if unknown:
        raise KeyError(
            "неизвестные сценарии: " + ", ".join(unknown)
            + "; доступны: " + ", ".join(_BY_ID))
    chosen = {_BY_ID[name] for name in wanted}
    return [s for s in SCENARIOS if s in chosen]


def expectations_of(scenario: Scenario) -> Mapping[str, Any]:
    return scenario.expectations()
