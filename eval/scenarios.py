@dataclass(frozen=True)
class Scenario:
    """Формулировка процесса + expectations, независимые от вывода модели."""

    id: str
    title: str
    text: str
    # минимальное число шагов (активностей), которое обязано дать это описание
    min_steps: int
    # сколько внешних участников оправдано текстом: лишние пулы = роли,
    # раздутые в участников
    max_pools: int
    must_branch: bool
    must_have_timer: bool
    expected_participants: Tuple[str, ...] = ()
    improve_prompt: str = ""
    source: str = ""
    tags: Tuple[str, ...] = field(default_factory=tuple)

    def expectations(self) -> Dict[str, Any]:
        """Словарь для `invariants.check_*`: только заявленные ожидания."""
        data: Dict[str, Any] = {
            "min_steps": self.min_steps,
            "max_pools": self.max_pools,
            "must_branch": self.must_branch,
            "must_have_timer": self.must_have_timer,
            "expected_participants": list(self.expected_participants),
        }
        return {k: v for k, v in data.items() if v not in (None, False, ())}


